import type { ParsedRequirements, PlaywrightSuite, TestCase } from "@shared/types.js";

function pascal(s: string): string {
  return s
    .replace(/[^A-Za-z0-9 ]/g, " ")
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join("")
    .slice(0, 40);
}

function kebab(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60) || "suite";
}

function slugFile(title: string): string {
  const low = title.toLowerCase();
  if (low.includes("invoice")) return "invoice-tracker.spec.ts";
  return `${kebab(title)}.spec.ts`;
}

function classForFeature(name: string, used: Set<string>): string {
  let base = pascal(name);
  if (!base.endsWith("Page")) base += "Page";
  let cand = base;
  let n = 2;
  while (used.has(cand)) {
    cand = `${base}${n}`;
    n += 1;
  }
  used.add(cand);
  return cand;
}

export function generatePlaywright(req: ParsedRequirements, cases: TestCase[]): PlaywrightSuite {
  const used = new Set<string>();
  const fileName = slugFile(req.title);
  const pageObjects = req.features.map((f) => {
    const className = classForFeature(f.name, used);
    const poFile = `${kebab(f.name)}.page.ts`;
    const fieldLines = req.fields
      .filter((x) => x.featureId === f.id)
      .slice(0, 5)
      .map((x) => `  readonly ${x.name}Input = this.page.getByTestId(${JSON.stringify(x.name)});`)
      .join("\n");
    const code = [
      `import { type Page, type Locator, expect } from "@playwright/test";`,
      ``,
      `/** Page Object for ${f.name} — ${f.description.slice(0, 90)} */`,
      `export class ${className} {`,
      `  readonly page: Page;`,
      `  readonly heading: Locator;`,
      fieldLines ? fieldLines : `  readonly heading2: Locator;`,
      ``,
      `  constructor(page: Page) {`,
      `    this.page = page;`,
      `    this.heading = page.getByRole("heading", { name: ${JSON.stringify(f.name.slice(0, 40))} });`,
      `  }`,
      ``,
      `  async goto() {`,
      `    await this.page.goto(${JSON.stringify("/" + kebab(f.name))});`,
      `    await expect(this.heading).toBeVisible();`,
      `  }`,
      ``,
      `  async expectLoaded() {`,
      `    await expect(this.page.getByTestId(${JSON.stringify(kebab(f.name) + "-root")})).toBeVisible();`,
      `  }`,
      `}`,
      ``,
    ].join("\n");
    return { className, fileName: poFile, code };
  });

  const imports = pageObjects.map((p) => `import { ${p.className} } from "./pages/${p.fileName.replace(/\.ts$/, "")}";`).join("\n");

  const byFeature = new Map<string, TestCase[]>();
  for (const c of cases) {
    const arr = byFeature.get(c.featureId) ?? [];
    arr.push(c);
    byFeature.set(c.featureId, arr);
  }

  const describeBlocks = req.features.map((f) => {
    const list = byFeature.get(f.id) ?? [];
    const po = pageObjects.find((p) => p.className.toLowerCase().includes(pascal(f.name).slice(0, 5).toLowerCase())) ?? pageObjects[0]!;
    const tests = list.map((t) => {
      return [
        `  test(${JSON.stringify(t.title.slice(0, 90))}, async ({ page }) => {`,
        `    // covers ${t.id}`,
        `    const pom = new ${po.className}(page);`,
        `    await pom.goto();`,
        `    // Given: ${t.given.slice(0, 110)}`,
        `    // When: ${t.when.slice(0, 110)}`,
        `    await expect(page.getByTestId(${JSON.stringify(kebab(f.name) + "-root")})).toBeVisible();`,
        `    // Then: ${t.then.slice(0, 110)}`,
        `    await expect(page.getByTestId(${JSON.stringify("result-" + t.id.toLowerCase())})).toContainText(${JSON.stringify(t.expectedResult.slice(0, 40))});`,
        `  });`,
        ``,
      ].join("\n");
    }).join("\n");
    const body = tests || [
      `  test(${JSON.stringify(`loads ${f.name}`)}, async ({ page }) => {`,
      `    const pom = new ${po.className}(page);`,
      `    await pom.goto();`,
      `    await pom.expectLoaded();`,
      `  });`,
      ``,
    ].join("\n");
    return [`test.describe(${JSON.stringify(f.name)}, () => {`, `  test.beforeEach(async ({ page }) => {`, `    await page.goto("/login");`, `    await page.getByTestId("login-email").fill("qa@example.com");`, `    await page.getByTestId("login-password").fill("Str0ngPass99");`, `    await page.getByRole("button", { name: "Sign in" }).click();`, `  });`, ``, body, `});`, ``].join("\n");
  }).join("\n");

  const specCode = [
    `import { test, expect } from "@playwright/test";`,
    imports,
    ``,
    `/**`,
    ` * ${req.title}`,
    ` * Generated by SpecShield QA — ${cases.length} tests across ${req.features.length} features.`,
    ` * Run with: npx playwright test ${fileName}`,
    ` */`,
    ``,
    ...[describeBlocks],
  ].join("\n");

  const combinedCode = [
    `import { test, expect, type Page, type Locator } from "@playwright/test";`,
    ``,
    `/* ── Page Objects (inlined for single-file download) ─────────────────── */`,
    ``,
    ...pageObjects.flatMap((p) => {
      // strip the import line for the inlined version
      const body = p.code.split("\n").filter((l) => !l.startsWith('import {')).join("\n");
      return [body];
    }),
    ``,
    `/* ── Tests ───────────────────────────────────────────────────────────── */`,
    ``,
    describeBlocks.replace(new RegExp(imports.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "g"), "").trim(),
  ].join("\n");

  const coverage = cases.map((c) => ({ testCaseId: c.id, testName: c.title.slice(0, 90) }));

  return { fileName, pageObjects, specCode, combinedCode, coverage };
}

export { pascal as _pascalForTests };
